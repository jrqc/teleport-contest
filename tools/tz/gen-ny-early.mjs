#!/usr/bin/env node
// tools/tz/gen-ny-early.mjs: writes js/crt/tz-ny-early.js, America/New_York local time
// types before 1955 (LMT, railroad standard time from 1883, the 1918-1954 daylight
// rules, war time EWT/EPT 1942-1945), from Darwin's own tz database through zdump
// (the recorder runs Darwin libc with TZ=America/New_York). js/crt/time.js codes
// 1955 onward as rules and uses this table before that.
// Usage: node tools/tz/gen-ny-early.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const out = execFileSync('zdump', ['-v', '-c', '1800,1956', 'America/New_York'], { encoding: 'utf8' });
const MON = { Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5, Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11 };
const rows = [];   // [utc start, gmtoff, isdst, abbr]
for (const line of out.split('\n')) {
    const m = line.match(/^\S+\s+\w+ (\w+)\s+(\d+) (\d+):(\d+):(\d+) (-?\d+) UT = .* (\w+) isdst=(\d) gmtoff=(-?\d+)$/);
    if (!m) continue;
    const t = Date.UTC(Number(m[6]), MON[m[1]], Number(m[2]), Number(m[3]), Number(m[4]), Number(m[5])) / 1000;
    const ty = [Number(m[9]), Number(m[8]), m[7]];
    const last = rows.at(-1);
    if (!last || last[1] !== ty[0] || last[2] !== ty[1] || last[3] !== ty[2]) rows.push([last ? t : -Infinity, ...ty]);
}
if (Number(rows.at(-1)[0]) < Date.UTC(1954, 0, 1) / 1000) throw new Error('zdump output ends before 1954');
const body = rows.map((r) => `    [${r[0] === -Infinity ? '-Infinity' : r[0]}, ${r[1]}, ${r[2]}, '${r[3]}'],`).join('\n');
writeFileSync(path.join(ROOT, 'js/crt/tz-ny-early.js'), `// js/crt/tz-ny-early.js: generated by tools/tz/gen-ny-early.mjs from Darwin's tz database
// (zdump -v -c 1800,1956 America/New_York). Do not edit.
// [UTC second the type starts, tm_gmtoff, tm_isdst, tm_zone], in time order; time.js uses
// it before the 1955 rules start.
export const NY_EARLY = [
${body}
];
`);
console.log(`${rows.length} local time types, ${rows[1][0]} .. ${rows.at(-1)[0]}`);
