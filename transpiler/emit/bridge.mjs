// bridge.mjs: generates nh/luabridge.js, the object-world entry points of the
// heap-world (Lua) functions NetHack calls (method/design.md 7.3).
//
// Each entry wraps the heap function with conversion descriptors derived from
// its C type (js/crt/bridge.js documents the kinds). Records the object world
// instantiates (luaL_Reg, lua_Debug) are copied across; records only the heap
// world looks into (lua_State, CallInfo) stay heap addresses.
import { EmitError } from './tu.mjs';
import { jsName } from './names.mjs';
import { AGGREGATE_NOTICE } from './comments.mjs';

/** Functions returning fresh memory the object world will use as a record: the size argument. */
const FRESH = { lua_newuserdatauv: 1 };

/** The parameter declarations of a C function type string (for const qualifiers). */
function paramTexts(ctype) {
    let end = ctype.length - 1;
    while (end >= 0 && ctype[end] !== ')') end--;
    let depth = 0, start = end;
    for (; start >= 0; start--) {
        if (ctype[start] === ')') depth++;
        else if (ctype[start] === '(') { depth--; if (depth === 0) break; }
    }
    const inner = ctype.slice(start + 1, end);
    const out = [];
    let d = 0, cur = '';
    for (const ch of inner) {
        if (ch === '(') d++;
        if (ch === ')') d--;
        if (ch === ',' && d === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
    }
    if (cur.trim()) out.push(cur.trim());
    return out.filter((x) => x !== '...' && x !== 'void');
}

export function bridgeModule(prog) {
    const records = new Map();   // key -> { scope }
    const objKeys = prog.objRecordKeys();
    const S0 = (d) => d.scope;
    function kind(S, t, isConst = false) {
        t = S.resolve(t);
        switch (t.k) {
        case 'void': return 'void';
        case 'int': return `${t.signed ? 'i' : 'u'}${t.size * 8}`;
        case 'float': return t.size === 4 ? 'f32' : 'f64';
        case 'arr': return { a: kind(S, t.of), n: t.n };
        case 'ptr': {
            const to = S.resolve(t.to);
            if (to.k === 'int' && to.size === 1) return 's';
            if (to.k === 'void') return 'v';
            if (to.k === 'fn') return { f: [kind(S, to.ret), ...(to.params || []).map((p) => kind(S, p))] };
            if (to.k === 'rec') {
                if (!objKeys.has(to.key)) return 'o';
                records.set(to.key, S);
                return { r: to.key, ro: isConst };
            }
            if (to.k === 'ptr' && S.resolve(to.to).k === 'int' && S.resolve(to.to).size === 1 && isConst) return 'S';
            return { p: kind(S, to) };
        }
        default: throw new EmitError(`bridge: no conversion for a ${t.k}`);
        }
    }
    const lines = [];
    const imports = new Map();
    const names = [...prog.bridgeFns.keys()].sort();
    for (const name of names) {
        const d = prog.bridgeFns.get(name);
        const S = S0(d);
        const ft = S.resolve(S.type(d.ctype));
        const consts = paramTexts(d.ctype).map((p) => /^const\b/.test(p));
        // a non-const char * parameter may be written (regerror's errbuf): 'sb', copied back
        const desc = [kind(S, ft.ret), ...(ft.params || []).map((p, i) => { const k = kind(S, p, consts[i]); return k === 's' && !consts[i] ? 'sb' : k; })];
        if (!imports.has(d.module)) imports.set(d.module, []);
        imports.get(d.module).push(name);
        const fresh = FRESH[name] !== undefined ? `, ${FRESH[name]}` : '';
        lines.push(`export const ${jsName(name)} = $b.toObj(H$${name}, ${JSON.stringify(desc)}${fresh});`);
        lines.push(`$b.register(${JSON.stringify(name)}, H$${name});`);
    }
    // the record tables (fields of records copied across); nested records are copied by their fields
    const recLines = [];
    const done = new Set();
    for (const [key, S] of records) {
        if (done.has(key)) continue;
        done.add(key);
        const L = S.recordLayout(key);
        const fields = [];
        for (const f of L.fields) {
            if (f.bits !== null) throw new EmitError(`bridge: bit-field ${key}.${f.name}`);
            fields.push(`[${JSON.stringify(f.js)}, ${f.offset}, ${JSON.stringify(kind(S, f.type))}]`);
        }
        recLines.push(`    ${JSON.stringify(key)}: { cls: () => $T.${prog.className(key, S)}, size: ${L.size}, fields: [${fields.join(', ')}] },`);
    }
    const out = [...AGGREGATE_NOTICE, '// luabridge.js: object-world entry points of heap-world (Lua) functions (generated by transpiler/emit/bridge.mjs). Do not edit.',
        "import * as $b from '../crt/bridge.js';", "import * as $T from './types.js';"];
    for (const [m, ns] of [...imports].sort()) out.push(`import { ${ns.sort().map((n) => `${jsName(n)} as H$${n}`).join(', ')} } from './${m}.js';`);
    out.push('', '$b.setRecords({', ...recLines.sort(), '});', '', ...lines, '');
    return out.join('\n');
}
