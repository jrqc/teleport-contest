#!/usr/bin/env node
// data.mjs: embed the recorder's data directory as JS modules (transpiler-design.md 8.1).
// Usage: node transpiler/emit/data.mjs [--out DIR]   (default transpiler/build/data)
// One module per file (a latin1 string literal, ASCII-escaped), plus index.js:
//   export const files = [[name, () => Uint8Array], ...]; export const dirs = [...]
// Taken from the reference recorder's install directory, so the bytes are what the
// recorder read. Left out: the binaries, and the files record-session.mjs deletes
// before a session (record, logfile, xlogfile, paniclog).
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync, rmSync } from 'node:fs';
import path from 'node:path';
import { ROOT } from '../frontend/ast.mjs';

const SRC = path.join(ROOT, 'tools/recorder-env/build/nethack-c/recorder/install/games/lib/nethackdir');
const args = process.argv.slice(2);
let out = path.join(ROOT, 'transpiler/build/data');
const oi = args.indexOf('--out');
if (oi >= 0) out = path.resolve(args[oi + 1]);
const SKIP = new Set(['nethack', 'recover', 'record', 'logfile', 'xlogfile', 'paniclog']);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const names = readdirSync(SRC).sort();
const files = [], dirs = [];
const lit = (b) => {
    let s = '"';
    for (const c of b) {
        if (c === 0x22) s += '\\"'; else if (c === 0x5c) s += '\\\\'; else if (c === 10) s += '\\n'; else if (c === 9) s += '\\t';
        else if (c >= 32 && c < 127) s += String.fromCharCode(c); else s += '\\x' + c.toString(16).padStart(2, '0');
    }
    return s + '"';
};
for (const name of names) {
    const full = path.join(SRC, name);
    if (statSync(full).isDirectory()) { dirs.push(name); continue; }
    if (SKIP.has(name)) continue;
    const mod = name.replace(/[^A-Za-z0-9_-]/g, '_') + '.js';
    const b = readFileSync(full);
    // split long literals into lines of ~100 bytes so diffs stay local
    const parts = [];
    for (let i = 0; i < b.length; i += 100) parts.push(lit(b.subarray(i, i + 100)));
    writeFileSync(path.join(out, mod), `// ${name}: embedded from the recorder's data directory (generated by transpiler/emit/data.mjs). Do not edit.\nexport default ${parts.length ? parts.join(' +\n    ') : '""'};\n`);
    files.push({ name, mod });
}
const idx = ['// index.js: the embedded data directory (generated by transpiler/emit/data.mjs). Do not edit.'];
files.forEach((f, i) => idx.push(`import f${i} from './${f.mod}';`));
idx.push('const bytes = (s) => { const b = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) b[i] = s.charCodeAt(i); return b; };');
idx.push('export const files = [');
files.forEach((f, i) => idx.push(`    [${JSON.stringify(f.name)}, () => bytes(f${i})],`));
idx.push('];', `export const dirs = ${JSON.stringify(dirs)};`, '');
writeFileSync(path.join(out, 'index.js'), idx.join('\n'));
console.log(`${files.length} files, ${dirs.length} dirs -> ${path.relative(ROOT, out)}`);
