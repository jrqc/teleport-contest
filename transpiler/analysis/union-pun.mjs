#!/usr/bin/env node
// union-pun.mjs: the per-union punning check (transpiler-design.md 3.4, D1).
//
// Input: the `unionCensus` facts in transpiler/out/inventory/tu/*.json
// (union-census-tu.mjs). Written member types propagate along value flows to a
// fixed point; a union is punning-possible if
//   (a) a member's address escapes (access kind `addr`), or
//   (b) in some storage class, a member type is read that differs from a
//       member type written into that class or flowing into it.
// Only unions with neither are "object"; all others are "union-cell" (heap).
// Output: transpiler/out/union-pun.json and transpiler/out/union-pun.md.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { ROOT } from '../frontend/ast.mjs';

const INV = path.join(ROOT, 'transpiler/out/inventory');
const unions = new Map();
const acc = new Map();          // dedup key -> access
const flows = new Map();        // "src\0dst" -> site
const params = [];
for (const f of readdirSync(path.join(INV, 'tu')).filter((x) => x.endsWith('.json')).sort()) {
    const c = JSON.parse(readFileSync(path.join(INV, 'tu', f), 'utf8')).unionCensus;
    if (!c) throw new Error(`${f}: no unionCensus (re-run run-inventory.mjs)`);
    for (const [k, u] of Object.entries(c.unions)) if (!unions.has(k)) unions.set(k, u);
    for (const a of c.acc) acc.set(`${a.u}|${a.t}|${a.k}|${a.c}|${a.file}:${a.line}`, a);
    for (const [s, d, site] of c.flow) { const k = `${s}\0${d}`; if (!flows.has(k)) flows.set(k, site); }
    params.push(...c.params);
}
// indirect calls: an argument may reach any union parameter at that position;
// a result may come from any function's return class
for (const [s, d, site] of [...flows].map(([k, v]) => [...k.split('\0'), v])) {
    const m = d.match(/^a:\?#(\d+)$/);
    if (m) for (const [fn, i] of params) if (String(i) === m[1]) flows.set(`${s}\0a:${fn}#${i}`, site);
}
const retClasses = new Set([...flows.keys()].map((k) => k.split('\0')[1]).filter((d) => d.startsWith('r:') && d !== 'r:?'));
for (const r of retClasses) flows.set(`${r}\0r:?`, 'indirect call');

// per class: union, written types (with an example site), read types
const cl = new Map();
const C = (c) => { if (!cl.has(c)) cl.set(c, { u: null, W: new Map(), R: new Map(), addr: [] }); return cl.get(c); };
for (const a of acc.values()) {
    const x = C(a.c);
    x.u = a.u;
    const site = `${a.file}:${a.line}${a.fn ? ' ' + a.fn : ''}`;
    if (a.k === 'w' || a.k === 'rw' || a.k === 'init') if (!x.W.has(a.t)) x.W.set(a.t, `${a.k} ${site}`);
    if (a.k === 'r' || a.k === 'rw') if (!x.R.has(a.t)) x.R.set(a.t, site);
    if (a.k === 'addr') x.addr.push(`&.${a.t} ${site}`);
}
const succ = new Map();
for (const k of flows.keys()) {
    const [s, d] = k.split('\0');
    C(s); C(d);
    if (!succ.has(s)) succ.set(s, []);
    succ.get(s).push(d);
}
// reaching written types: type -> "where written (class)"
const reach = new Map([...cl].map(([c, x]) => [c, new Map([...x.W].map(([t, s]) => [t, `${s} [${c}]`]))]));
const work = [...cl.keys()];
while (work.length) {
    const s = work.pop();
    for (const d of succ.get(s) || []) {
        const rd = reach.get(d);
        let changed = false;
        for (const [t, why] of reach.get(s)) if (!rd.has(t)) { rd.set(t, why); changed = true; }
        if (changed) work.push(d);
    }
}
// a class without accesses inherits its union from a neighbor (for reporting)
const res = {};
for (const [k, u] of [...unions].sort()) {
    res[k] = { file: u.file, line: u.line, members: u.members.map((m) => `${m.type} ${m.name}`), accesses: 0, classes: 0, verdict: 'object', puns: [], escapes: [] };
}
for (const a of acc.values()) if (res[a.u]) res[a.u].accesses++;
for (const [c, x] of cl) {
    if (!x.u || !res[x.u]) continue;
    const r = res[x.u];
    r.classes++;
    for (const e of x.addr) r.escapes.push(`${e} [${c}]`);
    for (const [rt, rsite] of x.R) for (const [wt, wwhy] of reach.get(c)) {
        if (rt !== wt) r.puns.push({ class: c, read: rt, readAt: rsite, written: wt, writtenAt: wwhy });
    }
}
for (const r of Object.values(res)) {
    if (r.puns.length || r.escapes.length) r.verdict = 'union-cell';
    r.punCount = r.puns.length;
    r.puns = r.puns.slice(0, 8);
    r.escapeCount = r.escapes.length;
    r.escapes = r.escapes.slice(0, 5);
}
writeFileSync(path.join(ROOT, 'transpiler/out/union-pun.json'), JSON.stringify(res, null, 1));

const isLua = (r) => r.file.startsWith('lib/lua');
const lines = ['# Union punning check (generated by transpiler/analysis/union-pun.mjs)', '',
    'Rule (design 3.4, decision D1): a union is an object only if no member address escapes and',
    'no storage class reads a member type other than one written into it or flowing into it.',
    'Every other union is heap-backed (a union cell). Lua unions are heap-backed anyway (heap mode).', '',
    '| Union | Defined | Accesses | Classes | Verdict | Pun pairs | Escapes |', '|---|---|---|---|---|---|---|'];
for (const [k, r] of Object.entries(res)) lines.push(`| \`${k}\` | ${r.file}:${r.line} | ${r.accesses} | ${r.classes} | ${isLua(r) ? 'heap (Lua)' : r.verdict} | ${r.punCount} | ${r.escapeCount} |`);
lines.push('', '## Evidence (first pun pairs and escapes per union)', '');
for (const [k, r] of Object.entries(res)) {
    if (r.verdict === 'object') continue;
    lines.push(`### \`${k}\`${isLua(r) ? ' (Lua)' : ''}`, '');
    for (const p of r.puns) lines.push(`- read \`${p.read}\` at ${p.readAt}, written \`${p.written}\` (${p.writtenAt}); class \`${p.class}\``);
    for (const e of r.escapes) lines.push(`- address escapes: ${e}`);
    lines.push('');
}
writeFileSync(path.join(ROOT, 'transpiler/out/union-pun.md'), lines.join('\n') + '\n');
const nh = Object.entries(res).filter(([, r]) => !isLua(r));
console.log(`unions: ${Object.keys(res).length} (nethack ${nh.length}); nethack object: ${nh.filter(([, r]) => r.verdict === 'object').length}, union-cell: ${nh.filter(([, r]) => r.verdict !== 'object').length}`);
for (const [k, r] of nh) console.log(`  ${r.verdict.padEnd(10)} ${k} (acc ${r.accesses}, puns ${r.punCount}, escapes ${r.escapeCount})`);
